def art_grid(art, letters, w, h):
    rows = art.strip('\n').split('\n')
    assert len(rows) == h, f"{len(rows)} rows, want {h}"
    for r in rows:
        assert len(r) == w, f"row {r!r} is {len(r)} wide, want {w}"
        for c in r:
            assert c in letters, f"unknown pixel {c!r}"
    return [[letters.index(c) for c in r] for r in rows]


def rotate_cw(g):
    """east-facing -> south-facing (front at the bottom)"""
    h, w = len(g), len(g[0])
    return [[g[h - 1 - y][x] for y in range(h)] for x in range(w)]


