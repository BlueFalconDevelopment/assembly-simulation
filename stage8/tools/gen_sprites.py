def grid(art):
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 16, f"{len(rows)} rows"
    for r in rows:
        assert len(r) == 16, f"row {r!r} is {len(r)} wide"
        for c in r:
            assert c in LETTERS, f"unknown pixel {c!r}"
    return rows


def sprites():
    out = []
    for pose in ORDER:
        for art in POSES[pose]:
            out.append([[LETTERS.index(c) for c in row] for row in grid(art)])
    return out


def nasm():
    lines = [";; ---- SPRITE DATA (generated by tools/gen_sprites.py; don't edit by hand) ----",
             "    ; 16x16 palette indices, one byte per pixel; sprite = pose * 2 + walk frame,",
             "    ; poses " + ", ".join(ORDER) + " (W, NW, SW are E, NE, SE mirrored)",
             "    soldier_sprites:"]
    for n, sp in enumerate(sprites()):
        lines.append(f"        ; {ORDER[n // 2]} frame {n % 2}")
        for row in sp:
            lines.append("        db " + ",".join(str(v) for v in row))
    lines.append("    SPRITE_COUNT equ ($ - soldier_sprites) / 256")
    for label, comment, grids in object_blocks() + ground_blocks():
        lines.append(f"    ; {comment}")
        lines.append(f"    {label}:")
        for g in grids:
            for row in g:
                lines.append("        db " + ",".join(str(v) for v in row))
    lines.append(";; ---- END SPRITE DATA ----")
    return "\n".join(lines)


def preview_objects(path):
    from PIL import Image
    cols = {'car': {1: (20, 20, 20), 2: (60, 60, 60), 3: (60, 80, 110), 4: (80, 100, 130), 5: (200, 30, 30),
                    6: (255, 240, 180), 7: (10, 10, 10), 8: (240, 240, 240), 9: (230, 30, 30), 10: (40, 80, 255)},
            'dog': {1: (160, 100, 60), 2: (110, 65, 40), 3: (20, 20, 20), 4: (160, 100, 60), 5: (110, 65, 40), 6: (200, 30, 30)},
            'pick': {1: (230, 210, 40), 2: (50, 50, 55), 3: (110, 110, 115), 4: (130, 80, 40)}}
    fam = {'cop_sprite_h': 'car', 'cop_sprite_v': 'car', 'dog_sprites': 'dog', 'pickup_sprites': 'pick'}
    scale = 6
    im = Image.new("RGB", (190 * scale, 45 * scale), (96, 140, 78))
    px = im.load()
    ox = 1
    for label, _, grids in object_blocks():
        for g in grids:
            for y, row in enumerate(g):
                for x, v in enumerate(row):
                    c = cols[fam[label]].get(v)
                    if c:
                        for dy in range(scale):
                            for dx in range(scale):
                                px[(ox + x) * scale + dx, (1 + y) * scale + dy] = c
            ox += len(g[0]) + 2
    im.save(path)


def preview(path):
    from PIL import Image
    pal = {0: None, 1: (40, 30, 25), 2: (60, 110, 210), 3: (190, 140, 100), 4: (60, 110, 210),
           5: (40, 75, 150), 6: (60, 60, 80), 7: (20, 20, 20), 8: (230, 190, 40), 9: (50, 50, 55),
           10: (90, 90, 95), 11: (220, 220, 230)}
    sps = sprites()
    scale = 8
    im = Image.new("RGB", (len(sps) * 18 * scale, 18 * scale), (96, 140, 78))
    px = im.load()
    for n, sp in enumerate(sps):
        for y, row in enumerate(sp):
            for x, v in enumerate(row):
                c = pal[v]
                if c:
                    for dy in range(scale):
                        for dx in range(scale):
                            px[(n * 18 + 1 + x) * scale + dx, (1 + y) * scale + dy] = c
    im.save(path)


if __name__ == "__main__":
    sp = sprites()
    print(f"ok: {len(sp)} sprites", file=sys.stderr)
    if len(sys.argv) > 2 and sys.argv[1] == "--write":
        src = open(sys.argv[2]).read()
        a = src.index(";; ---- SPRITE DATA")
        b = src.index(";; ---- END SPRITE DATA ----") + len(";; ---- END SPRITE DATA ----")
        open(sys.argv[2], "w").write(src[:a] + nasm() + src[b:])
    elif len(sys.argv) > 2 and sys.argv[1] == "--preview":
        preview(sys.argv[2])
    elif len(sys.argv) > 2 and sys.argv[1] == "--preview-objects":
        preview_objects(sys.argv[2])
    else:
        print(nasm())
